export type CaseTask = {
  id: string;
  title: string;
  /** Каталогтағы карточка үшін қысқа сипат. */
  summary: string;
  icon: IconName;
  accent: string;
  grade: string;
  duration: string;
  /** Кейс дамытатын икемді дағдылар — пәннің орнына сүзгі де, белгі де осы. */
  skills: SkillAxis[];
  intro: string;
  video: {
    youtubeId: string;
    title: string;
    source: string;
    /** Ұзақтығы белгілі болса ғана — болжам жазылмайды. */
    durationLabel?: string;
    /** Бейнеден нақты не іздеу керек. */
    watchFor: string[];
  };
  task: {
    prompt: string;
    hint: string;
    checklist: string[];
    /** Жауап осыдан қысқа болса, келесі қадам ашылмайды. */
    minChars: number;
  };
  roleplay: {
    scenario: string;
    goal: string;
    /** Нақты тәжірибе жасалатын кейсте — мұғалім алдын ала дайындайтын құралдар. */
    materials?: string[];
    roles: CaseRole[];
    rounds: CaseRound[];
    /** Достар жиналмағанда — өткізіп жіберудің орнына жалғыз орындау нұсқасы. */
    soloNote: string;
  };
  /** Кейс соңындағы рефлексия — сыныпта ауызша талқыланады. */
  discussion: string[];
};

