/* ------------------------------------------------------------------ *\
   Тест
\* ------------------------------------------------------------------ */
export type QuizQuestion =
  | { id: string; kind: "single"; prompt: string; options: string[]; answer: number; explain: string }
  | { id: string; kind: "multi"; prompt: string; options: string[]; answer: number[]; explain: string }
  | { id: string; kind: "boolean"; prompt: string; answer: boolean; explain: string };

export type QuizSpec = {
  id: string;
  title: string;
  /** Өту шегі, 0–100. */
  passScore: number;
  questions: QuizQuestion[];
};

/** «Дұрыс» / «Қате» нұсқалары — boolean сұрақтары үшін тұрақты рет. */
export const BOOLEAN_OPTIONS = ["Дұрыс", "Қате"] as const;

/** Кез келген сұрақтың нұсқалар тізімі (boolean да қоса). */
export function optionsOf(question: QuizQuestion): readonly string[] {
  return question.kind === "boolean" ? BOOLEAN_OPTIONS : question.options;
}

/** Күтілетін жауап индекстері — салыстыру үшін бірыңғай пішінге келтірілген. */
export function expectedIndices(question: QuizQuestion): number[] {
  if (question.kind === "single") return [question.answer];
  if (question.kind === "boolean") return [question.answer ? 0 : 1];
  return [...question.answer].sort((a, b) => a - b);
}

/**
 * Жауаптың дұрыстығы. `multi` толық сәйкестікпен бағаланады: жартылай ұпай
 * жоқ — оқушыға да, мұғалімнің рубрикасына да түсіндіру оңай.
 */
export function isAnswerCorrect(question: QuizQuestion, given: number[]): boolean {
  const expected = expectedIndices(question);
  const actual = [...given].sort((a, b) => a - b);
  return expected.length === actual.length && expected.every((v, i) => v === actual[i]);
}

export function scoreQuiz(spec: QuizSpec, answers: Record<string, number[]>) {
  const total = spec.questions.length;
  const correct = spec.questions.reduce(
    (sum, question) => sum + (isAnswerCorrect(question, answers[question.id] ?? []) ? 1 : 0),
    0,
  );
  return { correct, total, score: total === 0 ? 0 : Math.round((100 * correct) / total) };
}

