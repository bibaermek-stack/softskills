export function findLesson(id: string): Lesson | undefined {
  return lessons.find((lesson) => lesson.id === id);
}

/** Пән бойынша сабақ — пән бетінен сілтеу үшін. */
export function lessonForSubject(subject: SubjectId): Lesson | undefined {
  return lessons.find((lesson) => lesson.subject === subject);
}
