/**
 * Кейс тапсырмалары — платформаның дербес бөлімі.
 *
 * Сабақтар пән бойынша бөлінеді, ал кейстер бөлінбейді: мұнда өлшенетін нәрсе
 * пәндік білім емес, **икемді дағды** — бір-бірін тыңдау, әділ бөлісу, топта
 * рөл алу, жауапкершілік. Сондықтан әр кейс `SkillAxis` бойынша белгіленеді
 * (аналитикадағы дағды радарының дәл сол осьтері), пән бойынша емес.
 *
 * Әр кейс төрт қадамнан тұрады:
 *   1. Бейне       — жағдаятпен танысу
 *   2. Тапсырма     — қысқа жеке жауап, рөлдік ойынға дайындық
 *   3. Рөлдік ойын  — достарды шақырып ойнау; жиналмаса, өткізіп жіберуге болады
 *   4. Талқылау     — сыныпта ауызша қорытындылау
 */

import type { IconName } from "@/components/dashboard/Icon";
import type { SkillAxis } from "./lessons";

export type CaseRole = {
  id: string;
  name: string;
  emoji: string;
  /** Рөлдің басты мақсаты — карточкадағы бір жолдық түйін. */
  mission: string;
  /** Осы рөл орындайтын нақты іс. */
  brief: string[];
  /** Топтағы басқаларға қоятын сұрақтар. */
  asks: string[];
};

/**
 * Раундта бір рөлге қойылатын сұрақ.
 *
 * Сұрақ рөлге байланған: тәжірибе жасаушыдан тәжірибенің әділдігі сұралады,
 * бақылаушыдан — байқағанын қалай айту керегі. Сондықтан әркім өз сұрағын
 * алады да, жауаптарды қосқанда команданың ортақ нәтижесі шығады.
 */
export type CaseQuestion = {
  roleId: string;
  prompt: string;
  options: string[];
  correctIndex: number;
  explain: string;
};

export type CaseRound = {
  title: string;
  prompt: string;
  /** Раунд ұзақтығы — ойындағы таймер осыдан басталады. */
  minutes: number;
  /** Әр рөлге бір сұрақтан. */
  questions: CaseQuestion[];
};

export type CaseTask = {
  id: string;
  title: string;
  /** Каталогтағы карточка үшін қысқа сипат. */
  summary: string;
  icon: IconName;
  accent: string;
  grade: string;
  duration: string;
  /** Кейс дамытатын икемді дағдылар — пәннің орнына сүзгі де, белгі де осы. */
  skills: SkillAxis[];
  intro: string;
  video: {
    /** Бос болса — бейне әлі жүктелмеген, қадам орнын ұстап тұрады. */
    youtubeId?: string;
    title: string;
    source: string;
    /** Ұзақтығы белгілі болса ғана — болжам жазылмайды. */
    durationLabel?: string;
    /** Бейнеден нақты не іздеу керек. */
    watchFor: string[];
  };
  task: {
    prompt: string;
    hint: string;
    checklist: string[];
    /** Жауап осыдан қысқа болса, келесі қадам ашылмайды. */
    minChars: number;
  };
  roleplay: {
    scenario: string;
    goal: string;
    /** Нақты тәжірибе жасалатын кейсте — мұғалім алдын ала дайындайтын құралдар. */
    materials?: string[];
    roles: CaseRole[];
    rounds: CaseRound[];
    /** Достар жиналмағанда — өткізіп жіберудің орнына жалғыз орындау нұсқасы. */
    soloNote: string;
  };
  /** Кейс соңындағы рефлексия — сыныпта ауызша талқыланады. */
  discussion: string[];
};

